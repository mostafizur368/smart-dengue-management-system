"use strict";
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const firebase = JSON.parse(fs.readFileSync(path.join(root, "firebase.json"), "utf8"));
const deployRules = fs.readFileSync(path.join(root, firebase.firestore.rules), "utf8");
const reviewRules = fs.readFileSync(path.join(root, "firestore_rules_current.txt"), "utf8");
const findings = [];
const add = (severity, id, message) => findings.push({ severity, id, message });
if (deployRules !== reviewRules) add("CRITICAL", "RULES_COPY_MISMATCH", "The Firebase CLI deploy target differs from the review copy.");
if (!deployRules.includes("request.resource.data.keys().hasOnly([\n          'userId', 'patientName'")) add("HIGH", "APPOINTMENT_SCHEMA", "Appointment create schema allowlist is missing.");
if (deployRules.includes("allow create: if true;")) add("MEDIUM", "PUBLIC_CREATE", "At least one public create rule exists; verify its field validation and abuse controls.");
if (!deployRules.includes("existsAfter(appointmentPath)")) add("HIGH", "TICKET_ATOMICITY", "Ticket counter is not visibly linked to an appointment in the same atomic write.");
if (!deployRules.includes("match /security_events/{eventId}")) add("HIGH", "SECURITY_COLLECTIONS", "Security event access rules are missing.");
console.log(`Firebase deploy target: ${firebase.firestore.rules}`);
console.log(`Rules files identical: ${deployRules === reviewRules}`);
console.log(`Rules match blocks: ${(deployRules.match(/match\s+\//g) || []).length}`);
if (!findings.length) console.log("No configured static audit findings. This is not a penetration test or Emulator validation.");
else findings.forEach(item => console.log(`[${item.severity}] ${item.id}: ${item.message}`));
if (findings.some(item => ["CRITICAL", "HIGH"].includes(item.severity))) process.exitCode = 1;
